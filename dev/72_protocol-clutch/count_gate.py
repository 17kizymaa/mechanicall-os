#!/usr/bin/env python3
"""Count aether gate events. Prints aggregates and machine refuse lines only."""

from __future__ import annotations

import json
from collections import Counter
from datetime import datetime
from pathlib import Path

ROOTS = [
    ("tool", Path("/mnt/kingston-nixos-sync/opt/mechanicall-os/.aether/events.jsonl")),
    ("operator", Path("/home/anphuni/anphuni-project/.aether/events.jsonl")),
    ("server-ops", Path("/home/anphuni/server_ops/.aether/events.jsonl")),
]


def load(path: Path) -> list[dict]:
    if not path.exists():
        return []
    out = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if line:
            out.append(json.loads(line))
    return out


def shape(reason: str) -> str:
    r = (reason or "").strip()
    if r.upper() in {"APPROVED", "REJECTED", "YES", "NO", "OK"}:
        return "single-word"
    if len(r) == 0:
        return "empty"
    if len(r) < 40:
        return "short"
    if len(r) < 160:
        return "medium"
    return "long"


def section(name: str, events: list[dict]) -> list[str]:
    lines = [f"## {name}", ""]
    if not events:
        lines += ["(no events)", ""]
        return lines
    kinds = Counter(e.get("kind", "?") for e in events)
    lines.append(f"- events: {len(events)}")
    lines.append(f"- first: {events[0]['ts'][:10]}  last: {events[-1]['ts'][:19]}")
    lines.append("- kinds: " + ", ".join(f"{k} {v}" for k, v in kinds.most_common()))
    by = Counter(e.get("by", "(none)") for e in events if e.get("kind") in {"approve", "reject", "next_selected"})
    lines.append("- approve/reject/next by: " + ", ".join(f"{k} {v}" for k, v in by.most_common()))

    pf = [e for e in events if e.get("kind") == "preflight"]
    res = Counter(e.get("result", "?") for e in pf)
    lines.append("- preflight: " + ", ".join(f"{k} {v}" for k, v in res.most_common()))

    for kind in ("approve", "reject", "next_selected"):
        bucket = Counter(shape(e.get("reason", "")) for e in events if e.get("kind") == kind)
        if bucket:
            lines.append(f"- {kind} reasons: " + ", ".join(f"{k} {v}" for k, v in bucket.most_common()))

    lines += ["", "### Refuses", ""]
    refuses = [e for e in pf if e.get("result") == "refused"]
    if not refuses:
        lines.append("(none)")
    for e in refuses:
        reason = " ".join((e.get("reason") or "").split())
        lines.append(f"- {e['ts'][:19]}  `{e.get('action')}`  {reason}")

    lines += ["", "### Weeks", ""]
    wk: Counter[str] = Counter()
    wk_pf: Counter[str] = Counter()
    for e in events:
        # bucket by Monday date via %W label plus year
        d = datetime.fromisoformat(e["ts"].replace("Z", "+00:00"))
        key = f"{d.isocalendar().year}-W{d.isocalendar().week:02d}"
        wk[key] += 1
        if e.get("kind") == "preflight":
            wk_pf[key] += 1
    for key in sorted(wk):
        lines.append(f"- {key}: {wk[key]} events, {wk_pf[key]} preflights")
    lines.append("")
    return lines


def main() -> None:
    chunks = ["# Gate counts", "", "Generated by `dev/72_protocol-clutch/count_gate.py`. Machine fields only.", ""]
    for name, path in ROOTS:
        chunks.append(f"Source: `{path}`")
        chunks.append("")
        chunks.extend(section(name, load(path)))
    text = "\n".join(chunks).rstrip() + "\n"
    out = Path(__file__).resolve().parent / "output" / "COUNTS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
